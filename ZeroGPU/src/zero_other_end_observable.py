def bell():
    v = np.zeros(4)
    v[0] = v[3] = 1 / math.sqrt(2)
    return np.outer(v, v)


rho = bell()
rng = np.random.default_rng(42)


def proj(th):
    p = np.array([[math.cos(th), math.sin(th)], [math.sin(th), -math.cos(th)]])
    w, v = np.linalg.eigh(p)
    return [np.outer(v[:, k], v[:, k].conj()) for k in range(2)], w


def local_records(thA, thB, N=200000):
    """只生成【本地记录】：A 记自己的 ±1，B 记自己的 ±1。"""
    PsA, evA = proj(thA)
    PsB, evB = proj(thB)
    Pj = np.array([[np.real(np.trace(rho @ np.kron(PsA[i], PsB[j])))
                   for j in range(2)] for i in range(2)])
    Pj = np.clip(Pj, 0, None)
    Pj = Pj / Pj.sum()
    cdf = np.cumsum(Pj.flatten())
    idx = np.searchsorted(cdf, rng.random(N))
    return evA[idx // 2], evB[idx % 2]


