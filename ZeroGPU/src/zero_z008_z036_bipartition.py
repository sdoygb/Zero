# 数值：中心态 vs 非中心态的 CHSH
def chsh_of_rho(rho):
    """对给定 4x4 态算 CHSH 最优值（用 Horodecki 公式的简化版：直接优化）。"""
    # Bloche 参数化
    def bloch(r):
        sx = np.array([[0, 1], [1, 0]], complex)
        sy = np.array([[0, -1j], [1j, 0]], complex)
        sz = np.array([[1, 0], [0, -1]], complex)
        out = {}
        for nm, s in (("x", sx), ("y", sy), ("z", sz)):
            out["a" + nm] = np.real(np.trace(r @ np.kron(s, np.eye(2))))
            out["b" + nm] = np.real(np.trace(r @ np.kron(np.eye(2), s)))
        T = np.zeros((3, 3))
        for i, si in enumerate((sx, sy, sz)):
            for j, sj in enumerate((sx, sy, sz)):
                T[i, j] = np.real(np.trace(r @ np.kron(si, sj)))
        return out, T

    _, T = bloch(rho)
    # Horodecki: Smax = 2*sqrt(m1+m2) 其中 m1,m2 是 T^T T 的最大两个本征值
    ev = np.linalg.eigvalsh(T.T @ T)[::-1]
    return 2 * math.sqrt(max(0.0, ev[0] + ev[1]))


