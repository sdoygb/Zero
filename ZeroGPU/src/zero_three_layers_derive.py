"""
zero_three_layers_derive.py —— 尝试推导「三个层有不同的物理参数/粒子/引力」
==============================================================================
用户指令（2026-10-22）："'没有'不代表'不是'！！！要尝试推导"
即：不许以"库里没有"结案，必须真的试。

本脚本试五种推导路线，如实报告成败。

可用原料（全部库内已有）：
  底(物质) 格数 6  角 57.930000°  毁灭率 1.000
  中       格数 18 角 26.159311°  毁灭率 0.889
  顶       格数 4  角  5.910689°  毁灭率 0.000
  约束：θ_M+θ_C+θ_I = 90°（Z164 命题164.2）

五种尝试：
  T1 每层能级  -log w_h              （Z046 模 Hamiltonian）
  T2 每层质量  m ∝ M(θ_h)²           （Z121 振幅律）
  T3 每层相位  → 三代相位            （Z123 δ+2π(n-1)/3）
  T4 每层引力势 φ_h = -L⁺(n_h-n̄_h)  （Z033 离散泊松，分解性）
  T5 每层耦合  ∝ 1/sin²θ_h

结论：
  T1 可推但平凡（只是 w_h 的读数）
  T2 失败：给 1:1.68:1.89，而三代是 1:207:3477（差 3 个量级）
  T3 失败：三代间隔 120°（1/3圈）vs 三层角和 90°（2/8圈），两个不同的圆周分划
  T4 **成功但只是分解**：每层有自己的 φ_h（叠加），总和是**一个**势，不是三种引力
  T5 得到三个数，但**无库内依据**说它是耦合常数

★ 关键障碍：**「三层」（底/中/顶）≠「三代」（3 相邻比）**——两种不同划分。
  Z164 全文 0 次提"相邻比"；Z129 明说"所谓'3 代'＝seed 的 3 个相邻比"。

输出：results/zero_three_layers_derive.json / .txt
运行：cd ZeroGPU/src && /usr/bin/python3 zero_three_layers_derive.py
"""
from __future__ import annotations
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import zero_sim as zs  # noqa: E402

RES = os.path.join(HERE, "..", "results")
LOG: list[str] = []
CK: list[dict] = []


def P_(*a):
    s = " ".join(str(x) for x in a)
    LOG.append(s)
    print(s)


def ck(name, cond, detail=""):
    CK.append({"name": name, "pass": bool(cond), "detail": detail})
    P_("  [%s] %s %s" % ("PASS" if cond else "FAIL", name, detail))


P_("=" * 96)
P_("尝试推导「三个层有不同的物理参数/粒子/引力」 · zero_three_layers_derive.py")
P_("=" * 96)

LAB = ["底(物质)", "中", "顶"]
GRID = [6, 18, 4]
ANG = [57.930000, 26.159311, 5.910689]
DEST = [1.000, 0.889, 0.000]

P_("\n原料（库内已有）：")
for i in range(3):
    P_("  %-9s 格数=%2d  角=%10.6f°  毁灭率=%.3f"
       % (LAB[i], GRID[i], ANG[i], DEST[i]))
P_("  约束：三角度数之和 = %.6f°（Z164 命题164.2：=90°，只 2 个自由度）"
   % sum(ANG))
ck("原料：三角度数之和 = 90°（Z164 命题164.2）",
   abs(sum(ANG) - 90.0) < 1e-6, "sum = %.6f" % sum(ANG))

# ══════════════════════════════════════════════════════════════════
# T1 每层能级
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("T1 每层能级：-log w_h（Z046 模 Hamiltonian）")
P_("=" * 96)
s = float(sum(GRID))
w = [g / s for g in GRID]
lev = [-math.log(x) for x in w]
P_("  w_h = 格数/%d = %s" % (s, [round(x, 6) for x in w]))
P_("  -log w_h = %s" % [round(x, 6) for x in lev])
P_("  归一（最小=1）= %s" % [round(x / min(lev), 4) for x in lev])
P_("  ⟹ **可推**，但这只是 w_h 的读数，没有新物理")
ck("T1：每层能级 -log w_h 可推（但平凡）", True,
   "%s" % [round(x, 4) for x in lev])

# ══════════════════════════════════════════════════════════════════
# T2 每层质量（Z121 振幅律）
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("T2 每层质量：m ∝ M(θ_h)²，M(θ)=1+√2cosθ（Z121 振幅律）")
P_("=" * 96)
M = [1 + math.sqrt(2) * math.cos(math.radians(t)) for t in ANG]
m2 = [x * x for x in M]
rel = [x / min(m2) for x in m2]
P_("  M(θ_h) = %s" % [round(x, 6) for x in M])
P_("  m ∝ M²  = %s" % [round(x, 6) for x in m2])
P_("  质量比（最小=1）= %s" % [round(x, 4) for x in rel])
P_("  目标（三代，Z123）：1 : 206.77 : 3477.2")
P_("  ⟹ **失败**：只得到 ~1:1.7:1.9，差 3 个量级")
ck("T2：每层质量（振幅律）失败（1:1.68:1.89 vs 1:207:3477）", True,
   "rel = %s" % [round(x, 4) for x in rel])

# ══════════════════════════════════════════════════════════════════
# T3 每层相位 → 三代相位
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("T3 每层相位 → 三代相位（Z123：δ + 2π(n-1)/3，δ=2/9 rad）")
P_("=" * 96)
delta = 2.0 / 9.0
gen_ph = [math.degrees(delta) + 120 * k for k in range(3)]
P_("  三代相位 = %s 度" % [round(x, 4) for x in gen_ph])
P_("  三层角   = %s 度" % [round(x, 6) for x in ANG])
P_("  三代间隔 = 120° = 1/3 圈；三层角之和 = 90° = 2/8 圈")
P_("  ⟹ **失败**：两个不同的圆周分划，无直接同一迹象")
ck("T3：三层角与三代相位无对应（1/3 圈 vs 2/8 圈）", True,
   "gen=%s vs layers=%s" % ([round(x, 2) for x in gen_ph],
                            [round(x, 2) for x in ANG]))

# ══════════════════════════════════════════════════════════════════
# T4 每层引力势（分解性）
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("T4 每层引力势：φ_h = -L⁺(n_h - n̄_h)（Z033 离散泊松，分解性）")
P_("=" * 96)
K4 = zs.k4()
A = zs.adj_matrix(K4).astype(float)
Lm = np.diag(A.sum(1)) - A
Lp = np.linalg.pinv(Lm)
P_("  K4 的 L 谱 = %s" % [round(x, 4) for x in np.linalg.eigvalsh(Lm)])
P_("  若 n = Σ_h w_h n_h，则 φ = Σ_h w_h φ_h（叠加）")
modes = [np.array([1.0, -1.0, 0.0, 0.0]),
         np.array([0.0, 1.0, -1.0, 0.0]),
         np.array([0.0, 0.0, 1.0, -1.0])]
phis = []
P_("\n  %-6s %-26s %-26s" % ("层", "密度 n_h（示意）", "φ_h = -L⁺n_h"))
for i, nh in enumerate(modes):
    ph = -Lp @ nh
    phis.append(ph)
    P_("  %-6d %-26s %-26s"
       % (i + 1, str(np.round(nh, 2)), str(np.round(ph, 4))))
phis = np.array(phis)
S = np.sum(np.array(w)[:, None] * phis, axis=0)
P_("\n  合成 φ = Σ w_h φ_h = %s" % np.round(S, 4).tolist())
P_("  ⟹ **每层有自己的势 φ_h**（可推，成功）")
P_("  ⚠ 但总和是**一个**势 —— 是「三种贡献」，**不是三种引力**")
distinct = len({tuple(np.round(p, 6)) for p in phis}) == 3
ck("T4：每层各有自己的势 φ_h（分解成功）", distinct, "三层 φ_h 互不相同")
ck("T4（界限）：但合成是一个势，不是三种引力", True,
   "φ = Σ w_h φ_h 是叠加")

# ══════════════════════════════════════════════════════════════════
# T5 每层耦合常数
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("T5 每层耦合：∝ 1/sin²θ_h")
P_("=" * 96)
inv = [1.0 / (math.sin(math.radians(t)) ** 2) for t in ANG]
P_("  1/sin²θ_h = %s" % [round(x, 6) for x in inv])
P_("  ⟹ 得到三个数，但**无库内依据**说它是「每层的耦合常数」")
P_("  ⚠ 且 α⁻¹ = Σ_h 1/sin²θ_h + Σ_(i<j) 1/(sinθ_i sinθ_j) = 137 ——")
P_("     它们是**α 的分项**，不是三个独立常数")
ck("T5：1/sin²θ_h 只是 α 的分项，不是三个独立常数", True,
   "sum = %.4f" % sum(inv))

# ══════════════════════════════════════════════════════════════════
# 关键障碍：三层 ≠ 三代
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("★ 关键障碍：「三层」（底/中/顶）≠「三代」（3 相邻比）")
P_("=" * 96)
P_("""
  库里两处都叫「3 层／3 亚层」，但**划分不同**：

  ┌────────────┬──────────────────────────────────┬──────────────┐
  │ 出处        │ 「3 层」是什么                     │ 来自          │
  ├────────────┼──────────────────────────────────┼──────────────┤
  │ **Z161**   │ 4 顶点占据的 **3 个独立相邻比**     │ 计数（V-1=3） │
  │ **Z164**   │ **底／中／顶**（格数 6/18/4）       │ Z017 定理 7   │
  └────────────┴──────────────────────────────────┴──────────────┘

  **Z164 全文 0 次提「相邻比」**（实测）。
  **Z129 明说**："所谓'3 代'＝seed 的 3 个相邻比"。

  ⟹ **三代＝3 相邻比**；**三层角（底/中/顶）是另一套划分**。
  ⟹ 所以"每层一种粒子"若指 底/中/顶，则**它本身不是代**，不能直接当"三代粒子"。
""")
ck("★ 关键障碍：三层（底/中/顶）≠ 三代（3 相邻比）", True,
   "Z164 全文 0 次「相邻比」；Z129：3 代＝3 相邻比")

# ══════════════════════════════════════════════════════════════════
# 判定
# ══════════════════════════════════════════════════════════════════
P_("\n" + "=" * 96)
P_("判定：五种尝试的成败")
P_("=" * 96)
P_("""
  ┌──────┬────────────────────────────┬────────┬──────────────────────────┐
  │ 编号 │ 尝试                       │ 结果   │ 原因                     │
  ├──────┼────────────────────────────┼────────┼──────────────────────────┤
  │ T1   │ 每层能级 -log w_h          │ ✅ 可推 │ 但只是 w_h 的读数（平凡）│
  │ T2   │ 每层质量 ∝ M(θ_h)²         │ ❌ 失败 │ 1:1.68:1.89 ≠ 1:207:3477 │
  │ T3   │ 每层相位 → 三代            │ ❌ 失败 │ 1/3 圈 vs 2/8 圈         │
  │ T4   │ 每层引力势 φ_h             │ ✅ 成功 │ 但只是**分解**，非三种引力│
  │ T5   │ 每层耦合 ∝ 1/sin²θ_h       │ ⚠ 无依据│ 它们是 α 的分项          │
  └──────┴────────────────────────────┴────────┴──────────────────────────┘

  ⟹ **"每层不同"这个方向，在【引力分解】上成立（T4），
     在【粒子】上失败（T2/T3），在【参数】上只兑现 α（T5 是 α 的分项）。**

  ⟹ **根因**：**三层（底/中/顶）不是代的分划**——代是 3 相邻比（Z161/Z129）。
     所以"每层一种粒子"若要成立，必须先把 底/中/顶 与 三代 的关系说清；
     而库内**没有**这个关系。
""")
ck("★ 判定：T1/T4 可推（平凡/分解）；T2/T3 失败；T5 无依据", True,
   "根因：三层≠三代")

out = {
    "user_demand": "'没有'不代表'不是'，要尝试推导",
    "available": {"labels": LAB, "grid": GRID, "angles_deg": ANG,
                  "destruction": DEST, "constraint": "sum = 90 deg"},
    "attempts": {
        "T1_per_layer_level": {"result": "可推", "value": lev,
                               "caveat": "只是 w_h 的读数（平凡）"},
        "T2_per_layer_mass": {"result": "失败", "ratio": rel,
                              "target": "1 : 206.77 : 3477.2",
                              "reason": "差 3 个量级"},
        "T3_per_layer_phase": {"result": "失败",
                               "gen_phases": gen_ph,
                               "reason": "1/3 圈 vs 2/8 圈，两个圆周分划"},
        "T4_per_layer_gravity": {"result": "成功（分解）",
                                 "phi_h": phis.tolist(),
                                 "composite": S.tolist(),
                                 "caveat": "一个势的三种贡献，不是三种引力"},
        "T5_per_layer_coupling": {"result": "无依据", "values": inv,
                                  "caveat": "它们是 alpha 的分项"},
    },
    "key_obstacle": {
        "statement": "三层（底/中/顶，Z164）≠ 三代（3 相邻比，Z161/Z129）",
        "evidence": "Z164 全文 0 次提「相邻比」；Z129「所谓3代＝seed 的 3 个相邻比」",
    },
    "checks": CK,
    "verdict": ("试了五种推导：T1 每层能级可推但平凡；T2 每层质量失败"
                "（1:1.68:1.89 vs 1:207:3477）；T3 每层相位失败（1/3圈 vs 2/8圈）；"
                "T4 每层引力势成功但只是分解（一个势的三种贡献，不是三种引力）；"
                "T5 1/sin²θ 是 α 的分项不是独立常数。"
                "★ 根因：三层（底/中/顶）≠ 三代（3 相邻比）——两种不同划分，"
                "Z164 全文 0 次提相邻比。故'每层一种粒子'要成立，"
                "必须先建立 底/中/顶 与 三代 的关系，而库内没有这个关系。"),
}
os.makedirs(RES, exist_ok=True)
with open(os.path.join(RES, "zero_three_layers_derive.json"), "w",
          encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
with open(os.path.join(RES, "zero_three_layers_derive.txt"), "w",
          encoding="utf-8") as f:
    f.write("\n".join(LOG))
n_fail = sum(1 for c in CK if not c["pass"])
P_("\n判据 %d/%d PASS" % (len(CK) - n_fail, len(CK)))
P_("已存 results/zero_three_layers_derive.json / .txt")
sys.exit(1 if n_fail else 0)